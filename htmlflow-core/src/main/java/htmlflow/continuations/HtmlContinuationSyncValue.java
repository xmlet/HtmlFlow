package htmlflow.continuations;

import htmlflow.exceptions.HtmlFlowAppendException;
import htmlflow.visitor.HtmlVisitor;
import htmlflow.visitor.Tags;
import htmlflow.visitor.escape.HtmlEscapers;
import java.io.IOException;
import java.util.function.Function;
import java.util.function.Predicate;
import java.util.function.ToDoubleFunction;
import java.util.function.ToIntFunction;
import java.util.function.ToLongFunction;

/**
 * HtmlContinuation for a single value read from the model. The markup around the value lives in
 * the preencoded static blocks on either side.
 *
 * @author Bernardo Pereira
 */
public class HtmlContinuationSyncValue extends HtmlContinuationSync {

    public enum Kind {
        /** Written as is. */
        RAW,
        /** HTML escaped. */
        TEXT,
        INT,
        LONG,
        DOUBLE,
        BOOLEAN,
        /** An attribute we skip when the accessor returns null. */
        ATTR_NULLABLE,
    }

    private final Kind kind;
    private final Object accessor;

    /** Only set for ATTR_NULLABLE. */
    private final String attributeName;

    /**
     * Sets indentation to -1 to inform that visitor should continue with previous indentation.
     * A value slot changes neither the depth nor the isClosed of the visitor.
     */
    public HtmlContinuationSyncValue(
        Kind kind,
        Object accessor,
        String attributeName,
        HtmlVisitor visitor,
        HtmlContinuation next
    ) {
        super(-1, false, visitor, next);
        this.kind = kind;
        this.accessor = accessor;
        this.attributeName = attributeName;
    }

    public Kind kind() {
        return kind;
    }

    public Object accessor() {
        return accessor;
    }

    public String attributeName() {
        return attributeName;
    }

    /**
     * @apiNote The generated bytecode calls this by name. Renaming it makes compiled chains fall
     *     back to the linked chain.
     */
    public static String text(Object value) {
        return HtmlEscapers.htmlEscaper().escape(String.valueOf(value));
    }

    /**
     * Appends a value. A StringBuilder takes numbers without a String copy, which matters on
     * pages with many numbers.
     *
     * @apiNote The generated bytecode calls the append methods by name, same as {@link #text}.
     */
    public static void append(Appendable out, int value) throws IOException {
        if (out instanceof StringBuilder) {
            ((StringBuilder) out).append(value);
        } else {
            out.append(Integer.toString(value));
        }
    }

    public static void append(Appendable out, long value) throws IOException {
        if (out instanceof StringBuilder) {
            ((StringBuilder) out).append(value);
        } else {
            out.append(Long.toString(value));
        }
    }

    public static void append(Appendable out, double value) throws IOException {
        if (out instanceof StringBuilder) {
            ((StringBuilder) out).append(value);
        } else {
            out.append(Double.toString(value));
        }
    }

    public static void append(Appendable out, boolean value)
        throws IOException {
        if (out instanceof StringBuilder) {
            ((StringBuilder) out).append(value);
        } else {
            out.append(Boolean.toString(value));
        }
    }

    /** Appends String.valueOf(value), so null prints as "null". */
    public static void append(Appendable out, Object value) throws IOException {
        if (out instanceof StringBuilder) {
            ((StringBuilder) out).append(value);
        } else {
            out.append(String.valueOf(value));
        }
    }

    /** @apiNote The generated bytecode calls this by name, same as {@link #text}. */
    public static void attrNullable(Appendable out, String name, Object value) {
        if (value != null) Tags.addAttribute(out, name, String.valueOf(value));
    }

    /** Reads a value slot and appends it. The hot reload visitor shares this with the chain. */
    @SuppressWarnings("unchecked")
    public static void appendValue(
        Appendable out,
        Kind kind,
        Object accessor,
        Object model
    ) {
        try {
            switch (kind) {
                case INT:
                    append(
                        out,
                        ((ToIntFunction<Object>) accessor).applyAsInt(model)
                    );
                    break;
                case LONG:
                    append(
                        out,
                        ((ToLongFunction<Object>) accessor).applyAsLong(model)
                    );
                    break;
                case DOUBLE:
                    append(
                        out,
                        ((ToDoubleFunction<Object>) accessor).applyAsDouble(
                                model
                            )
                    );
                    break;
                case BOOLEAN:
                    append(out, ((Predicate<Object>) accessor).test(model));
                    break;
                case TEXT:
                    out.append(
                        text(((Function<Object, ?>) accessor).apply(model))
                    );
                    break;
                default:
                    append(out, ((Function<Object, ?>) accessor).apply(model));
            }
        } catch (IOException e) {
            throw new HtmlFlowAppendException(e);
        }
    }

    @SuppressWarnings("unchecked")
    @Override
    protected final void emitHtml(Object model) {
        if (kind == Kind.ATTR_NULLABLE) {
            attrNullable(
                visitor.out(),
                attributeName,
                ((Function<Object, ?>) accessor).apply(model)
            );
        } else {
            appendValue(visitor.out(), kind, accessor, model);
        }
    }

    @Override
    public HtmlContinuation copy(HtmlVisitor v) {
        return new HtmlContinuationSyncValue(
            kind,
            accessor,
            attributeName,
            v,
            next != null ? next.copy(v) : null
        );
    }
}
